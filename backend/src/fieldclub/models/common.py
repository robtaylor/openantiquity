"""Column helpers shared by every model file."""

from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime
from enum import StrEnum
from typing import Annotated, Any

from geoalchemy2 import Geometry, WKBElement, WKTElement
from geoalchemy2.shape import from_shape, to_shape
from shapely.geometry import Point
from shapely.geometry.base import BaseGeometry
from sqlalchemy import BigInteger, CheckConstraint, DateTime, ForeignKey, Identity, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import MappedColumn, mapped_column

SRID = 4326

# `id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`
IdPk = Annotated[int, mapped_column(BigInteger, Identity(), primary_key=True)]

# `created_at timestamptz NOT NULL DEFAULT now()`
CreatedAt = Annotated[datetime, mapped_column(DateTime(timezone=True), server_default=func.now())]

TimestampTz = DateTime(timezone=True)

JsonDict = dict[str, Any]


def fk(target: str, *, ondelete: str | None = None, index: bool = False, **kwargs: Any) -> MappedColumn[Any]:
    """A `BIGINT` foreign key column. Nullability comes from the `Mapped[...]` annotation."""
    return mapped_column(BigInteger, ForeignKey(target, ondelete=ondelete), index=index, **kwargs)


# Python None is stored as SQL NULL, not as the JSON value `null`, so that
# `IS NULL` means what it says.
JsonB = JSONB(none_as_null=True)


def json_column(**kwargs: Any) -> MappedColumn[Any]:
    return mapped_column(JsonB, **kwargs)


def enum_check(column: str, enum_cls: type[StrEnum]) -> CheckConstraint:
    """A `CHECK` that keeps a `TEXT` column inside a `StrEnum`.

    Enumerations are stored as text, not as native PostgreSQL enums, so this is
    what stops a typo reaching the table. A `CHECK` passes when it is NULL, so
    a nullable column needs nothing more: nullability comes from the
    `Mapped[...]` annotation.

    The check names its column and enumeration in `info`, so that
    `fieldclub.db.create_schema` can make it again in a database built
    before the enumeration last changed.
    """
    return CheckConstraint(
        enum_check_text(column, enum_cls), name=f"{column}_valid", info={"column": column, "enum": enum_cls}
    )


def values_check_text(column: str, values: Sequence[str]) -> str:
    """The condition that the column is one of `values`."""
    assert values, f"no values for the check on {column}"
    assert all("'" not in value for value in values), f"a value for {column} has a quote in it"
    quoted = ", ".join(f"'{value}'" for value in values)
    return f"{column} IN ({quoted})"


def enum_check_text(column: str, enum_cls: type[StrEnum]) -> str:
    """The condition of an `enum_check`: the column is one of the enumeration's values."""
    return values_check_text(column, [member.value for member in enum_cls])


def point(*, spatial_index: bool = True) -> Geometry:
    return Geometry("POINT", srid=SRID, spatial_index=spatial_index)


def polygon(*, spatial_index: bool = True) -> Geometry:
    return Geometry("POLYGON", srid=SRID, spatial_index=spatial_index)


def multipolygon(*, spatial_index: bool = True) -> Geometry:
    return Geometry("MULTIPOLYGON", srid=SRID, spatial_index=spatial_index)


def any_geometry(*, spatial_index: bool = True) -> Geometry:
    return Geometry("GEOMETRY", srid=SRID, spatial_index=spatial_index)


def to_db_geometry(geometry: BaseGeometry) -> WKBElement:
    """A shapely geometry as a value for a geometry column."""
    return from_shape(geometry, srid=SRID)


def db_point(lon: float, lat: float) -> WKBElement:
    """A WGS84 point as a value for a geometry column."""
    return to_db_geometry(Point(lon, lat))


def point_lon_lat(value: WKBElement | WKTElement, what: str = "the value") -> tuple[float, float]:
    """Longitude and latitude of a point read from a geometry column. `what` names it in the assertion."""
    point = to_shape(value)
    assert isinstance(point, Point), f"{what} has a non-point location: {point.geom_type}"
    return point.x, point.y
