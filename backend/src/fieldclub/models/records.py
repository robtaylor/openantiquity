"""The heritage record index: sources, records, ingest runs, the gazetteer and admin areas."""

from __future__ import annotations

from datetime import datetime

from geoalchemy2 import WKBElement
from sqlalchemy import (
    Boolean,
    CheckConstraint,
    FetchedValue,
    Float,
    ForeignKey,
    Index,
    Integer,
    Text,
    UniqueConstraint,
    true,
)
from sqlalchemy.dialects.postgresql import ARRAY, TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from fieldclub.db import Base
from fieldclub.models.common import (
    CreatedAt,
    IdPk,
    JsonDict,
    TimestampTz,
    any_geometry,
    enum_check,
    json_column,
    multipolygon,
    point,
)
from fieldclub.vocab import AdminAreaKind, IngestStatus, Nation, RecordCategory, SourceAccess, SourceReuse


class Source(Base):
    """An external dataset. Its licence and attribution are stored before any of its data is."""

    __tablename__ = "sources"
    __table_args__ = (enum_check("access", SourceAccess), enum_check("reuse", SourceReuse))

    key: Mapped[str] = mapped_column(Text, primary_key=True)
    created_at: Mapped[CreatedAt]
    name: Mapped[str] = mapped_column(Text)
    publisher: Mapped[str] = mapped_column(Text)
    licence: Mapped[str] = mapped_column(Text)
    licence_url: Mapped[str | None] = mapped_column(Text)
    attribution: Mapped[str] = mapped_column(Text)
    # What the licence allows, per Decision 0004. No default: every source
    # has to say.
    reuse: Mapped[str] = mapped_column(Text)
    homepage: Mapped[str | None] = mapped_column(Text)
    coverage: Mapped[str | None] = mapped_column(Text)
    # A record category for sources that feed the index. Other sources (elevation,
    # imagery, map tiles) name their own kind, so this column is not constrained.
    category: Mapped[str] = mapped_column(Text)
    access: Mapped[str] = mapped_column(Text)
    record_count: Mapped[int | None] = mapped_column(Integer)
    last_ingest_at: Mapped[datetime | None] = mapped_column(TimestampTz)
    enabled: Mapped[bool] = mapped_column(Boolean, default=True, server_default=true())


class Record(Base):
    """One heritage record from one source. Never edited here, only re-ingested."""

    __tablename__ = "records"
    __table_args__ = (
        UniqueConstraint("source_key", "external_id"),
        enum_check("category", RecordCategory),
        # ST_PointOnSurface gives POINT EMPTY for some odd geometries. A row
        # like that is invisible to every distance query, so refuse it.
        CheckConstraint("NOT ST_IsEmpty(centroid)", name="centroid_not_empty"),
        Index(
            "ix_records_name_trgm", "name", postgresql_using="gin", postgresql_ops={"name": "gin_trgm_ops"}
        ),
    )

    id: Mapped[IdPk]
    created_at: Mapped[CreatedAt]
    source_key: Mapped[str] = mapped_column(Text, ForeignKey("sources.key", ondelete="CASCADE"))
    external_id: Mapped[str] = mapped_column(Text)
    name: Mapped[str] = mapped_column(Text)
    summary: Mapped[str | None] = mapped_column(Text)
    category: Mapped[str] = mapped_column(Text, index=True)
    record_type: Mapped[str | None] = mapped_column(Text)
    monument_types: Mapped[list[str] | None] = mapped_column(ARRAY(Text))
    periods: Mapped[list[str] | None] = mapped_column(ARRAY(Text))
    geom: Mapped[WKBElement] = mapped_column(any_geometry())
    # A point guaranteed to lie on the geometry. extras.sql indexes it as geography.
    centroid: Mapped[WKBElement] = mapped_column(point(spatial_index=False))
    # How exact the position is. A find published to a 1 km square has 1000.
    precision_m: Mapped[float | None] = mapped_column(Float)
    url: Mapped[str | None] = mapped_column(Text)
    raw: Mapped[JsonDict | None] = json_column()
    source_updated_at: Mapped[datetime | None] = mapped_column(TimestampTz)
    ingested_at: Mapped[datetime] = mapped_column(TimestampTz)
    # Generated by PostgreSQL. extras.sql adds the column and its GIN index,
    # because the expression needs a helper function that must exist first.
    # `system=True` keeps it out of CREATE TABLE and out of every INSERT.
    search: Mapped[str | None] = mapped_column(TSVECTOR, FetchedValue(), system=True, deferred=True)

    def __repr__(self) -> str:
        return f"<Record {self.source_key}:{self.external_id} {self.name!r}>"


class IngestRun(Base):
    __tablename__ = "ingest_runs"
    __table_args__ = (enum_check("status", IngestStatus),)

    id: Mapped[IdPk]
    created_at: Mapped[CreatedAt]
    source_key: Mapped[str] = mapped_column(Text, ForeignKey("sources.key", ondelete="CASCADE"), index=True)
    started_at: Mapped[datetime] = mapped_column(TimestampTz)
    finished_at: Mapped[datetime | None] = mapped_column(TimestampTz)
    status: Mapped[str] = mapped_column(Text)
    stats: Mapped[JsonDict | None] = json_column()
    error: Mapped[str | None] = mapped_column(Text)


class Place(Base):
    """A named place for the search box."""

    __tablename__ = "places"
    __table_args__ = (
        enum_check("nation", Nation),
        Index("ix_places_name_trgm", "name", postgresql_using="gin", postgresql_ops={"name": "gin_trgm_ops"}),
    )

    id: Mapped[IdPk]
    created_at: Mapped[CreatedAt]
    name: Mapped[str] = mapped_column(Text)
    kind: Mapped[str] = mapped_column(Text)
    district: Mapped[str | None] = mapped_column(Text)
    county: Mapped[str | None] = mapped_column(Text)
    nation: Mapped[str | None] = mapped_column(Text)
    geom: Mapped[WKBElement] = mapped_column(point())
    # Bigger places rank higher and come first in search results.
    rank: Mapped[int] = mapped_column(Integer)
    source: Mapped[str] = mapped_column(Text)


class AdminArea(Base):
    """A nation or county boundary, used to say where a point is.

    A nation row's `code` is its `vocab.Nation` value, such as `england`.
    """

    __tablename__ = "admin_areas"
    __table_args__ = (
        UniqueConstraint("kind", "code"),
        enum_check("kind", AdminAreaKind),
    )

    id: Mapped[IdPk]
    created_at: Mapped[CreatedAt]
    kind: Mapped[str] = mapped_column(Text)
    code: Mapped[str] = mapped_column(Text)
    name: Mapped[str] = mapped_column(Text)
    geom: Mapped[WKBElement] = mapped_column(multipolygon())


__all__ = ["AdminArea", "IngestRun", "Place", "Record", "Source"]
