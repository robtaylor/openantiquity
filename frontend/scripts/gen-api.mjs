// Regenerate src/api/schema.d.ts from the backend's OpenAPI document.
//
// Runs `uv run fieldclub-openapi` in ../backend, which prints the schema as JSON,
// and hands it to openapi-typescript. Nothing is written unless both succeed.
// Then type-checks scripts/schema-compat.ts, which fails if the backend's
// /meta no longer fits the hand-written types the app is built on.
import { spawnSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

class GenApiError extends Error {
  constructor(message) {
    super(message);
    this.name = "GenApiError";
  }
}

const here = dirname(fileURLToPath(import.meta.url));
const frontend = resolve(here, "..");
const backend = resolve(frontend, "../backend");
const output = resolve(frontend, "src/api/schema.d.ts");

const HEADER = `/**
 * Generated by \`pnpm gen:api\` from the backend's OpenAPI document.
 * Do not edit by hand: change the backend schemas and regenerate.
 */

`;

function readSchema() {
  if (!existsSync(resolve(backend, "pyproject.toml"))) {
    throw new GenApiError(
      `No backend project at ${backend}. gen:api needs the backend checked out beside the frontend.`,
    );
  }
  const result = spawnSync("uv", ["run", "fieldclub-openapi"], {
    cwd: backend,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) {
    const hint = result.error.code === "ENOENT" ? " Is uv installed and on your PATH?" : "";
    throw new GenApiError(`Could not run "uv run fieldclub-openapi": ${result.error.message}.${hint}`);
  }
  if (result.status !== 0) {
    throw new GenApiError(
      `"uv run fieldclub-openapi" exited with status ${result.status} in ${backend}:\n${result.stderr.trim()}`,
    );
  }
  let schema;
  try {
    schema = JSON.parse(result.stdout);
  } catch (cause) {
    throw new GenApiError(`"uv run fieldclub-openapi" did not print JSON: ${cause.message}`);
  }
  if (typeof schema !== "object" || schema === null || typeof schema.openapi !== "string" || !schema.paths) {
    throw new GenApiError('"uv run fieldclub-openapi" printed JSON that is not an OpenAPI document.');
  }
  return schema;
}

function checkCompatibility() {
  const result = spawnSync(
    process.execPath,
    [resolve(frontend, "node_modules/typescript/bin/tsc"), "-p", "tsconfig.schema.json"],
    {
      cwd: frontend,
      encoding: "utf8",
    },
  );
  if (result.error) throw new GenApiError(`Could not run the TypeScript compiler: ${result.error.message}`);
  if (result.status !== 0) {
    throw new GenApiError(
      `The generated types no longer fit the hand-written ones:\n${(result.stdout + result.stderr).trim()}\n` +
        "The backend's /meta has changed. Bring src/api/meta.ts and the code that uses it into line, or fix the backend.",
    );
  }
}

try {
  const schema = readSchema();
  const ast = await openapiTS(schema);
  writeFileSync(output, HEADER + astToString(ast));
  console.log(`Wrote ${output} from OpenAPI ${schema.openapi} (${Object.keys(schema.paths).length} paths).`);
  checkCompatibility();
  console.log("The generated /meta types fit src/api/meta.ts.");
} catch (error) {
  if (!(error instanceof GenApiError)) throw error;
  console.error(`gen:api failed. ${error.message}`);
  process.exit(1);
}
